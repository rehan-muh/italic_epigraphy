# ---------------------------------------------------------------- helpers
def tex_int(n):
    return f"{n:,}".replace(",", "{,}")


def macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def corpus_stats():
    con = sqlite3.connect(ROOT / "db" / "atlas.sqlite")
    total = con.execute("select count(*) from inscriptions").fetchone()[0]
    bylang = con.execute("""
        select coalesce(l.name,'(unrecorded)'), count(*),
               sum(case when i.direction_id is not null then 1 else 0 end)
        from inscriptions i left join languages l on l.id=i.language_id
        group by 1 order by 2 desc""").fetchall()
    codes = dict(con.execute("""
        select d.code, count(*) from inscriptions i
        join directions d on d.id=i.direction_id group by 1""").fetchall())
    pile = con.execute("""
        select count(*) from inscriptions i join quarters q
        on q.ord = i.q_ord_start where q.edge = -400""").fetchone()[0]
    widths = [r[0] for r in con.execute("""
        select i.q_ord_end - i.q_ord_start + 1 from inscriptions i
        join directions i2 on i2.id = i.direction_id
        where i.q_ord_start is not null""").fetchall()]
    con.close()
    return total, bylang, codes, pile, np.array(widths)


