bs2 = chr(92)
def write_table(name, colspec, header, rows):
    """A complete tabular: input inside an alignment cannot cross EOF,
    so each table ships as one whole environment."""
    L = [bs2 + 'begin{tabular}{' + colspec + '}',
         bs2 + 'hline' + bs2 + 'hline',
         header + ' ' + bs2 + bs2,
         bs2 + 'hline'] + rows + [bs2 + 'hline' + bs2 + 'hline',
         bs2 + 'end{tabular}']
    (REP / ('tab_' + name + '.tex')).write_text(chr(10).join(L) + chr(10), encoding='utf-8')



