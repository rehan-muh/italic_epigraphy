def fig_coverage(bylang):
    c = F.Canvas()
    W, RH = 6.0, 0.34
    langs = [(l, t, cd or 0) for l, t, cd in bylang if t >= 40]
    top = len(langs) * RH
    mx = max(t for _, t, _ in langs)
    for v in (0, 5000, 10000):
        x = v / mx * W
        c.add(F.Line([(x, 0), (x, top)], F.mix(F.RULE, 60)))
        c.add(F.Text(x, top, f"{v:,}", "above", 2))
    y = top
    for lang, tot, cod in langs:
        y -= RH
        cy = y + RH / 2
        c.add(F.Text(0, cy, lang, "left", 4))
        c.add(F.Rect(0, cy - 0.09, tot / mx * W, cy + 0.09, F.mix(F.MID, 30), fill=True))
        if cod:
            c.add(F.Rect(0, cy - 0.09, cod / mx * W, cy + 0.09, F.mix(F.LTR, 75), fill=True))
        c.add(F.Text(tot / mx * W + 0.05, cy, f"{100*cod/tot:.0f}\\%", "right", 2))
    c.add(F.Text(W / 2, 0, "inscriptions (dark: direction coded)", "below", 8))
    return c


def fig_widths(widths):
    c = F.Canvas()
    W, H = 6.4, 2.6
    bins = [(1, "25 yr"), (2, "50"), (3, "75"), (4, "100"), (8, "200"),
            (12, "300"), (16, "400"), (999, "over 400")]
    counts, prev = [], 0
    w = widths[np.isfinite(widths)]
    for ub, _ in bins:
        counts.append(int(((w > prev) & (w <= ub)).sum()))
        prev = ub
    mx = max(counts)
    bw = W / len(bins)
    for i, ((_, lab), n) in enumerate(zip(bins, counts)):
        x = i * bw
        c.add(F.Rect(x + 0.06, 0, x + bw - 0.06, n / mx * H, F.mix(F.LTR, 70), fill=True))
        c.add(F.Text(x + bw / 2, n / mx * H, f"{n:,}", "above", 2))
        c.add(F.Text(x + bw / 2, 0, lab, "below", 2))
    c.add(F.Text(W / 2, -0.42, "width of the dating interval", "below", 3))
    return c


def fig_map():
    import direction_model as D
    df, *_ = D.load()
    g = df.groupby("place_id").agg(x=("px", "first"), y=("py", "first"),
                                   n=("y", "size"), p=("y", "mean"))
    c = F.Canvas()
    W = 6.2
    x0, x1 = g.x.min(), g.x.max()
    y0, y1 = g.y.min(), g.y.max()
    Hm = W * (y1 - y0) / (x1 - x0)
    for _, r in g.iterrows():
        px = (r.x - x0) / (x1 - x0) * W
        py = (r.y - y0) / (y1 - y0) * Hm
        rad = max(0.018, min(0.12, (r.n ** 0.5) / 45))
        c.add(F.Dot(px, py, rad, F.colour(r.p)))
    c.add(F.Text(W / 2, -0.1,
                 "findspots, sized by inscriptions, coloured by share dextroverse",
                 "below", 3))
    return c


def fig_sweep():
    sel = M["st_kernel"].get("selection", [])
    best = {}
    for s in sel:
        key = (s["kernel"], s["length_scale_km"])
        if "lt" in s:
            continue
        best[key] = min(best.get(key, 9e9), s["cv_neg_loglik"])
    if not best:
        return None
    c = F.Canvas()
    W, H = 5.2, 2.6
    lss = sorted({k[1] for k in best})
    vals = [v for v in best.values()]
    lo, hi = min(vals), max(vals)
    pad = (hi - lo) * 0.15 + 1e-9

    def X(ls): return (lss.index(ls) / max(len(lss) - 1, 1)) * W
    def Y(v): return (v - lo + pad) / (hi - lo + 2 * pad) * H

    for kern, col, lab in [("se", F.mix(F.MID, 70), "squared-exponential"),
                           ("m32", F.LTR, "Mat\\`ern 3/2")]:
        pts = [(X(ls), Y(best[(kern, ls)])) for ls in lss if (kern, ls) in best]
        if not pts:
            continue
        c.add(F.Line(pts, col, width=1.2))
        for p in pts:
            c.add(F.Dot(p[0], p[1], 0.06, col))
        c.add(F.Text(pts[-1][0] + 0.1, pts[-1][1], lab, "right", 2, col=col))
    for ls in lss:
        c.add(F.Text(X(ls), 0, f"{ls:.0f} km", "below", 3))
    c.add(F.Text(0, H / 2, "held-out loss", "above", 16, rotate=90))
    c.add(F.Text(W / 2, -0.4, "kernel length scale (best ridge per point)", "below", 3))
    return c


def fig_forest():
    geo = M.get("geography", {})
    ct = M.get("contact_test", {})
    entries = [(f"corpus-wide: {k.replace('d_', 'distance to ')}",
                v["odds_ratio"], v.get("or_lo"), v.get("or_hi"))
               for k, v in geo.items()]
    if ct:
        d = ct["d_latin"]
        entries.append(("Etruscan alphabets only: distance to Latin",
                        d["odds_ratio"], d.get("or_lo"), d.get("or_hi")))
    c = F.Canvas()
    W, RH = 5.6, 0.34
    top = len(entries) * RH
    lo_x, hi_x = 0.55, 1.45

    def X(v): return (min(max(v, lo_x), hi_x) - lo_x) / (hi_x - lo_x) * W

    for v in (0.6, 0.8, 1.0, 1.2, 1.4):
        c.add(F.Line([(X(v), 0), (X(v), top)],
                     F.RULE if v == 1.0 else F.mix(F.RULE, 55), dashed=(v == 1.0)))
        c.add(F.Text(X(v), top, f"{v:g}", "above", 2))
    y = top
    for lab, orr, lo, hi in entries:
        y -= RH
        cy = y + RH / 2
        c.add(F.Text(0, cy, lab, "left", 4))
        if lo is not None and hi is not None:
            c.add(F.Line([(X(lo), cy), (X(hi), cy)], F.mix(F.MID, 85), width=1.0))
        c.add(F.Dot(X(orr), cy, 0.07, F.LTR if orr < 1 else F.mix(F.RTL, 80, F.MID)))
    c.add(F.Text(W / 2, 0, "odds ratio per log-km (95\\% cluster bootstrap)", "below", 8))
    return c


